'use strict';
const assert=require('node:assert/strict');
const M=require('../public/experience-model');
const L=require('../functions/logic');
const now=Date.parse('2026-11-17T15:00:00Z');
const iso=t=>new Date(t).toISOString();
const lastInferredRecount={count:30,timestamp:iso(now-30*60000),verified:false};
const occupancyEstimate={count:41,experimental:true,ageMinutes:30};
const d={dataState:'live',count:50,sourceUpdated:iso(now),lastInferredRecount,occupancyEstimate};
assert.deepEqual(M.liveContext(d,now),{live:true,recount:lastInferredRecount,estimate:occupancyEstimate});
assert.equal(M.liveContext(d,now+5*60000).estimate,null);
assert.equal(M.liveContext({...d,occupancyEstimate:null,estimatedNow:42},now).estimate,null);
assert.equal(M.liveContext({...d,lastInferredRecount:{count:40,timestamp:iso(now+60000)}},now).recount,null);
const cells=[];for(let dayIndex=0;dayIndex<7;dayIndex++)for(let hour=7;hour<23;hour++)cells.push({dayIndex,hour,average:hour===22?0:hour===21?1:20+hour,samples:60,days:3});
const windows=M.historyWindows(cells,now);
assert.equal(windows.length,7);
assert.equal(new Set(windows.map(x=>x.date)).size,7);
assert.ok(windows.every(x=>x.end<=M.close(x.dow)-60));
const heat=L.heatmap({'6-22':{sum:60,n:2,days:1},'0-22':{sum:20,n:2,days:1}});
assert.equal(heat.filter(x=>x.closed).length,2);
assert.ok(heat.filter(x=>x.closed).every(x=>x.average===null&&x.samples===0));
const H=require('../functions/history');
const profile=[];for(let dow=0;dow<7;dow++)for(let hour=7;hour<23;hour++)profile.push({dayIndex:dow,hour,average:hour<11?12:hour<17?40:hour<20?63:95,days:3,samples:60,closed:hour>=M.close(dow)/60});
const quiet=M.historyWindows(profile,now,7,{preference:'quiet',duration:60});
const social=M.historyWindows(profile,now,7,{preference:'social',duration:90,period:'evening'});
const balanced=M.historyWindows(profile,now,7,{preference:'balanced',duration:120,period:'afternoon'});
assert.ok(quiet.every(w=>w.average===12&&w.end-w.start===60));
assert.ok(social.length===7&&social.every(w=>w.average===63&&w.start>=1020&&w.end-w.start===90));
assert.ok(balanced.length===7&&balanced.every(w=>w.average===40&&w.start>=720&&w.end<=1020));
assert.ok(!M.historyWindows([],now,7,{preference:'social'}).length);
const model={points:[{minute:420,count:25},{minute:435,count:null},{minute:450,count:null}],summary:{coveredSlots:1}};
const fallback={points:[{minute:420,count:90},{minute:435,count:32},{minute:450,count:null}]};
const filled=H.fillForecastGaps(model,fallback);
assert.equal(filled.points[0].count,25);assert.equal(filled.points[1].count,32);assert.equal(filled.points[2].count,null);
assert.equal(filled.summary.coveredSlots,2);
assert.equal(H.fillForecastGaps(null,fallback),fallback);
const quietForecast={...d,count:65,forecast:{points:Array.from({length:53},(_,i)=>({minutes:i*15,count:i<8?65:i<16?30:55}))}};
const later=M.quieterLater(quietForecast,now);
assert.equal(later.state,'recommended');
assert.equal(later.average,30);
assert.ok(later.start> M.parts(now).minute);
assert.equal(later.end-later.start,60);
assert.ok(later.end<=M.close(M.parts(now).dow)-60);
assert.deepEqual(M.quieterLater({...quietForecast,count:20},now),{state:'not_quieter'});
assert.equal(M.quieterLater({...quietForecast,dataState:'delayed'},now).state,'unavailable');
assert.equal(M.quieterLater(quietForecast,now+5*60000).state,'unavailable');
const nearClose=Date.parse('2026-11-17T03:00:00Z');
assert.equal(M.quieterLater({...quietForecast,sourceUpdated:iso(nearClose)},nearClose).state,'no_window');
assert.equal(M.quieterLater({...quietForecast,dataState:'closed'},now).state,'closed');
const withPoints=(stamp,points,modelVersion='recount-seasonal-v4')=>({
 ...d,sourceUpdated:iso(stamp),forecast:{modelVersion,points:points.map(([minutes,count])=>({minutes,count}))}
});
const sparse=withPoints(now,[[0,50],[30,25],[75,25],[90,20]]);
assert.equal(M.quieterLater(sparse,now).state,'unavailable','A gap between exact forecast points cannot qualify as a full hour');
assert.deepEqual(M.thresholdWindows(sparse,now,{duration:60}),[]);
// The forecast arrives between planner quarter-hour boundaries.
// Inspect the actual forecast peaks and integrate the line over the session.
const misaligned=withPoints(now-3*60000,[[0,20],[10,80],[15,20],[30,20],[45,20],[60,20],[75,20]]);
const [first]=M.thresholdWindows(misaligned,now,{duration:60});
assert.deepEqual(first,{start:600,end:660,average:27,peak:80,source:'forecast'});
assert.equal(M.pickWindows([first],75)[0].peak,80);
const taperAt=Date.parse('2026-11-17T02:00:00Z'); // Monday, 9 PM Eastern
const taper=withPoints(taperAt,Array.from({length:9},(_,i)=>[i*15,i<4?50:Math.max(0,50-(i-4)*13)]),'v3-recount-provisional');
assert.equal(M.quieterLater(taper,taperAt).state,'no_window');
assert.deepEqual(M.thresholdWindows(taper,taperAt,{duration:60}),[]);
const dense=withPoints(now,Array.from({length:49},(_,i)=>[i*15,20]));
const matches=M.pickWindows(M.thresholdWindows(dense,now,{duration:90}),25);
assert.equal(matches.length,3);
assert.ok(matches.every((w,i)=>!i||matches[i-1].end<=w.start));
assert.ok(matches.every(w=>w.peak===20&&w.end<=1320));
console.log('Experience tests passed');
