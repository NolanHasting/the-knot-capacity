'use strict';
const assert=require('node:assert/strict');
const M=require('../public/experience-model');
const L=require('../functions/logic');
const now=Date.parse('2026-11-17T15:00:00Z');
const iso=t=>new Date(t).toISOString();
const d={dataState:'live',count:50,sourceUpdated:iso(now),todayHistory:[{count:40,timestamp:iso(now-31*60000)},{count:30,timestamp:iso(now-30*60000)},{count:50,timestamp:iso(now)}],recountModel:{departuresPerMinute:.3,rateSamples:3}};
assert.equal(M.liveContext(d,now).recount.count,30);
assert.equal(M.liveContext(d,now).estimate.count,41);
assert.equal(M.liveContext(d,now+5*60000).estimate,null);
assert.equal(M.liveContext({...d,todayHistory:[],recountModel:{}},now).estimate.basis,'reported');
assert.equal(M.liveContext({...d,todayHistory:[],recountModel:{}},now).estimate.count,50);
const cells=[];for(let dayIndex=0;dayIndex<7;dayIndex++)for(let hour=7;hour<23;hour++)cells.push({dayIndex,hour,average:hour===22?0:hour===21?1:20+hour,samples:60,days:3});
const windows=M.historyWindows(cells,now);
assert.equal(windows.length,7);
assert.equal(new Set(windows.map(x=>x.date)).size,7);
assert.ok(windows.every(x=>x.end<=M.close(x.dow)-60));
const heat=L.heatmap({'6-22':{sum:60,n:2,days:1},'0-22':{sum:20,n:2,days:1}});
assert.equal(heat.filter(x=>x.closed).length,2);
assert.ok(heat.filter(x=>x.closed).every(x=>x.average===null&&x.samples===0));
const forecast={...d,forecast:{points:Array.from({length:53},(_,i)=>({minutes:i*15,count:30+(i%4)}))}};
const today=M.todayWindow(forecast,now);assert.ok(today&&today.end-today.start===120&&today.end<=1350);
assert.equal(M.todayWindow({...forecast,dataState:'delayed'},now),null);
console.log('Experience tests passed');
