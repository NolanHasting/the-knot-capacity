'use strict';
const assert=require('node:assert/strict');
const F=require('../functions/feedback');
const token='12345678-1234-1234-1234-123456789abc';
const base={clientId:token,kind:'crowd',onSite:true,crowd:'busy',accuracy:'lower',count:'40'};
assert.equal(F.validateFeedback(base).report.observedCount,40);
assert.equal(F.validateFeedback({...base,count:''}).report.observedCount,null);
assert.throws(()=>F.validateFeedback({...base,onSite:false}));
assert.throws(()=>F.validateFeedback({...base,count:-1}));
assert.throws(()=>F.validateFeedback({...base,count:true}));
assert.throws(()=>F.validateFeedback({...base,contact:'person@example.com'}));
assert.throws(()=>F.validateFeedback({...base,contact:'person@example.com',contactConsent:'true'}));
assert.equal(F.validateFeedback({...base,contact:'person@example.com',contactConsent:true}).contact,'person@example.com');
assert.throws(()=>F.validateFeedback({clientId:token,kind:'suggestion',message:' '}));
assert.equal(F.validateFeedback({clientId:token,kind:'suggestion',message:'Improve chart'}).report.message,'Improve chart');
const now=new Date('2026-11-17T15:00:00Z');
assert.equal(F.context({sourceUpdated:'2026-11-17T14:58:00Z',open:true,count:32},now).reportedCount,32);
assert.equal(F.context({sourceUpdated:'2026-11-17T14:50:00Z',open:true,count:32},now).reportedCount,null);
console.log('Feedback tests passed');
